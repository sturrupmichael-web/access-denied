// Builds index.html: one self-contained page with the game's JavaScript, the content in
// data/ and the CSS inlined, so it runs on any static host and straight from disk. Edit the
// code under src/ and data/, play it with dev.html, then run `npm run build`.

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const js = await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
});
const inlineCss = (_, href) => `<style>\n${readFileSync(href, 'utf8').trim()}\n  </style>`;
const html = readFileSync('dev.html', 'utf8')
  .replace(/<link rel="stylesheet" href="([^"]+)">/g, inlineCss)
  .replace('<script type="module" src="src/main.js"></script>', () =>
    `<script type="module">\n${js.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script>`,
  )
  .replace('<title>', '<!-- Generated by build.mjs from dev.html, src/ and data/. Do not edit by hand. -->\n  <title>');
writeFileSync('index.html', withCsp(html));
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB`);

// Content Security Policy: the page may only run its own (inline, hashed) scripts and
// load nothing from anywhere else.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return page.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`);
}
